#!/usr/bin/env python3
"""Kev vs Jev on bench-linguist: where and why the open model loses → KEV-VS-JEV.md.

    python3 benchmarks/bench-linguist/analysis/kev_vs_jev.py

Both ran the same protocol (tools/jev_linguist.py: the file's content, Linguist's 804 languages
in 4 seeded groups of ~200 with "none of these", then a final among the winners), so their raw
logs (entries/raw/{kev,jev}-linguist.jsonl: group winners, final probabilities) can be compared
file by file. Adds the results of kev_order_experiment.py when present.
"""

from __future__ import annotations

import json
import random
import statistics
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
BENCH = HERE.parent
ROOT = BENCH.parents[1]
sys.path.insert(0, str(ROOT / "tools"))
from score import name_key, outcome, read_cases  # noqa: E402

SWH = "https://archive.softwareheritage.org"


def pct(a, b):
    return f"{100 * a / b:.1f} %" if b else "—"


def main() -> int:
    cases = read_cases(BENCH)
    raw = {lab: {json.loads(line)["case_id"]: json.loads(line)
                 for line in (BENCH / "entries" / "raw" / f"{lab}.jsonl").read_text(encoding="utf-8").splitlines()}
           for lab in ("kev-linguist", "jev-linguist")}
    ling = json.loads((ROOT / "tools" / "data" / "linguist_languages.json").read_text(encoding="utf-8"))["languages"]
    names = sorted(lg["name"] for lg in ling)
    random.Random(20261002).shuffle(names)
    groups = [names[i::4] for i in range(4)]
    pos = {n: (gi, g.index(n), len(g)) for gi, g in enumerate(groups) for n in g}
    keys = {name_key(n): n for n in names}

    def ok(cid, lab):
        ch = raw[lab][cid]["choice"]
        return outcome(cases[cid], [ch] if ch else None) == "right"

    def stage(cid, lab):
        if ok(cid, lab):
            return "right"
        exp = next((keys[name_key(a)] for a in cases[cid]["accept"].split(";") if a and name_key(a) in keys), None)
        if exp is None:
            return "not in the list"
        w = raw[lab][cid]["group_winners"]
        if exp in w:
            return "lost in the final"
        return ("lost in its group: another language" if any(pos[x][0] == pos[exp][0] for x in w if x in pos)
                else "lost in its group: \"none of these\"")

    ids = list(cases)
    agree = Counter((ok(c, "jev-linguist"), ok(c, "kev-linguist")) for c in ids)
    jev_only = [c for c in ids if ok(c, "jev-linguist") and not ok(c, "kev-linguist")]
    out = ["# Kev vs Jev on bench-linguist", "",
           "Generated by `python3 benchmarks/bench-linguist/analysis/kev_vs_jev.py`. Both models ran the same "
           "protocol — the file's content only, GitHub Linguist's 804 languages asked in 4 seeded groups of ~200 "
           "(with \"none of these\"), then a final among the groups' winners — Jev 1.13 through OpenRouter, Kev-4B "
           "(an open decision model, Q8_0) locally with llama.cpp. Failure reports: "
           "[Kev](../FAILURES-kev-linguist.md), [Jev](../FAILURES-jev-linguist.md).", "",
           f"Kev is right on {pct(sum(ok(c, 'kev-linguist') for c in ids), len(ids))} of the {len(ids):,} files, "
           f"Jev on {pct(sum(ok(c, 'jev-linguist') for c in ids), len(ids))}. "
           f"**Jev is right and Kev wrong on {agree[(True, False)]} files**; the reverse on {agree[(False, True)]}; "
           f"both right on {agree[(True, True)]}, both wrong on {agree[(False, False)]}.", ""]

    # 1. where in the knockout
    st = {lab: Counter(stage(c, lab) for c in ids) for lab in raw}
    st747 = Counter(stage(c, "kev-linguist") for c in jev_only)
    rows = ["lost in its group: another language", "lost in its group: \"none of these\"", "lost in the final",
            "not in the list"]
    out += ["## 1. Where the expected language is lost", "",
            f"| stage | Kev | Jev | Kev, on the {len(jev_only)} files Jev gets right |", "|---|---:|---:|---:|"]
    out += [f"| {r} | {st['kev-linguist'][r]} | {st['jev-linguist'][r]} | {st747[r]} |" for r in rows]
    nw = {lab: Counter(len(raw[lab][c]["group_winners"]) for c in ids) for lab in raw}
    out += ["", "Kev rarely answers \"none of these\" in a group that does not hold the file's language, so more "
            "languages reach the final:", "", "| groups sending a winner | 0 | 1 | 2 | 3 | 4 |", "|---|---:|---:|---:|---:|---:|"]
    out += [f"| {lab.split('-')[0].capitalize()} | " + " | ".join(str(nw[lab][k]) for k in range(5)) + " |" for lab in raw]

    # 2. primacy
    dec = {lab: Counter(min(9, int(10 * pos[w][1] / pos[w][2])) for c in ids for w in raw[lab][c]["group_winners"]
                        if w in pos) for lab in raw}
    out += ["", "## 2. Kev favours the options listed first", "",
            "Each group lists its ~200 languages in a fixed (seeded) order. Where in that order do the groups' "
            "winners sit? A model that reads every option equally would spread them evenly over the deciles.", "",
            "| decile of the position in the group | " + " | ".join(str(i + 1) for i in range(10)) + " |",
            "|---|" + "---:|" * 10]
    out += [f"| {lab.split('-')[0].capitalize()} | " + " | ".join(str(dec[lab][i]) for i in range(10)) + " |"
            for lab in raw]
    wrong = Counter(raw["kev-linguist"][c]["choice"] for c in jev_only if raw["kev-linguist"][c]["choice"])
    out += ["", f"Kev's most frequent answers on the {len(jev_only)} files Jev gets right — mostly languages listed "
            "at the very start of their group:", "", "| Kev's answer | files | position in its group |", "|---|---:|---:|"]
    out += [f"| {a} | {n} | {pos[a][1] + 1} of {pos[a][2]} |" if a in pos else f"| {a} | {n} | — |"
            for a, n in wrong.most_common(12)]
    late = sorted(((pos[n][1] / pos[n][2], n) for n in names), reverse=True)[:40]
    late_ids = [c for c in ids if cases[c]["expected"] in {n for _, n in late}]
    out += ["", f"Conversely, the files whose language is listed in the last 5 % of its group ({len(late_ids)} files): "
            f"Kev {pct(sum(ok(c, 'kev-linguist') for c in late_ids), len(late_ids))}, Jev "
            f"{pct(sum(ok(c, 'jev-linguist') for c in late_ids), len(late_ids))} — e.g. Swift, listed 198th of 201: "
            + ", ".join(f"Kev {sum(ok(c, lab) for c in ids if cases[c]['expected'] == 'Swift')}"
                        if lab == "kev-linguist" else f"Jev {sum(ok(c, lab) for c in ids if cases[c]['expected'] == 'Swift')}"
                        for lab in raw) + f" of {sum(1 for c in ids if cases[c]['expected'] == 'Swift')} files."]

    # 3. what kind of files
    out += ["", "## 3. Which files", "", "| | files | Kev | Jev |", "|---|---:|---:|---:|"]
    for t in ("programming", "data", "markup", "prose"):
        s = [c for c in ids if cases[c]["type"] == t]
        out.append(f"| Linguist type: {t} | {len(s)} | {pct(sum(ok(c, 'kev-linguist') for c in s), len(s))} | "
                   f"{pct(sum(ok(c, 'jev-linguist') for c in s), len(s))} |")
    size = {c: (BENCH / "files" / cases[c]["sha1_git"]).stat().st_size for c in ids}
    for lo, hi in ((0, 300), (300, 1000), (1000, 4000), (4000, 16000), (16000, None)):
        s = [c for c in ids if size[c] >= lo and (hi is None or size[c] < hi)]
        out.append(f"| size {lo:,}–{hi:,} bytes |".replace("–None", "+") if hi else f"| size ≥ {lo:,} bytes |")
        out[-1] += f" {len(s)} | {pct(sum(ok(c, 'kev-linguist') for c in s), len(s))} | {pct(sum(ok(c, 'jev-linguist') for c in s), len(s))} |"
    for tag in ("seen-in-training", "unseen", "ambiguous-ext", "by-filename"):
        s = [c for c in ids if tag in cases[c]["tags"]]
        out.append(f"| tag `{tag}` | {len(s)} | {pct(sum(ok(c, 'kev-linguist') for c in s), len(s))} | "
                   f"{pct(sum(ok(c, 'jev-linguist') for c in s), len(s))} |")
    gap = Counter(cases[c]["expected"] for c in jev_only)
    out += ["", "Languages most often right for Jev and wrong for Kev: "
            + ", ".join(f"{lang} ({n})" for lang, n in gap.most_common(15)) + "."]

    # 4. confidence
    conf = {lab: {True: [], False: []} for lab in raw}
    for lab in raw:
        for c in ids:
            t5 = raw[lab][c].get("final_top5") or []
            if t5:
                conf[lab][ok(c, lab)].append(t5[0][1])
    out += ["", "## 4. Confidence of the final", "",
            "Top probability of the final (files with two finalists or more):", "",
            "| | median when right | median when wrong |", "|---|---:|---:|"]
    out += [f"| {lab.split('-')[0].capitalize()} | {statistics.median(conf[lab][True]):.2f} | "
            f"{statistics.median(conf[lab][False]):.2f} |" for lab in raw if conf[lab][True] and conf[lab][False]]

    # 5. experiment
    exp_p = HERE / "kev_order_experiment.jsonl"
    if exp_p.exists():
        er = [json.loads(line) for line in exp_p.read_text(encoding="utf-8").splitlines()]
        strata = {}
        for r in er:
            strata.setdefault(r["stratum"], set()).add(r["case_id"])
        out += ["", "## 5. Experiment: is it the option order?", "",
                "On a fixed sample (`kev_order_experiment.py`, seed 20261003) of 100 files Jev gets right and Kev "
                "wrong, and 50 files both get right, Kev is asked again in three ways: the same groups in reverse "
                "order; 16 groups of ~50 options instead of 4 of ~200; and PL-ultimate-llm's candidates for the "
                "file's extension first (as `tools/jev_cascade.py`, file name not shown). Right answers:", "",
                "| variant | of the files Jev gets right and Kev wrong | of the files both get right |", "|---|---:|---:|"]
        jo, bo = sorted(strata.get("jev-only", ())), sorted(strata.get("both", ()))
        out.append(f"| as run (4 groups of ~200) | 0/{len(jo)} | {len(bo)}/{len(bo)} |")
        labels = {"reversed": "same groups, reverse order", "small": "16 groups of ~50",
                  "cascade": "the extension's candidates first"}
        for v, lab in labels.items():
            rv = [r for r in er if r["variant"] == v]
            if rv:
                a = sum(r["right"] for r in rv if r["stratum"] == "jev-only")
                b = sum(r["right"] for r in rv if r["stratum"] == "both")
                na = sum(1 for r in rv if r["stratum"] == "jev-only")
                nb = sum(1 for r in rv if r["stratum"] == "both")
                out.append(f"| {lab} | {a}/{na} | {b}/{nb} |")
        wrong_rev = Counter(r["choice"] for r in er if r["variant"] == "reversed" and r["stratum"] == "jev-only"
                            and not r["right"] and r["choice"])
        if wrong_rev:
            out += ["", "With the order reversed, the first options of the original order (Ecere Projects, Move) "
                    "disappear from Kev's wrong answers, and the last ones come in — the order, not the content, "
                    "moves the answer: " + ", ".join(
                        f"{a} ({n}; listed {pos[a][1] + 1} of {pos[a][2]} as run, {pos[a][2] - pos[a][1]} reversed)"
                        if a in pos else f"{a} ({n})" for a, n in wrong_rev.most_common(4)) + "."]
        out += ["", "The candidates first recover most of the gap: with a handful of options, Kev's primacy bias "
                "has little room. Smaller groups help less, and reversing the order trades errors for others."]

    # 6. examples
    out += ["", "## 6. Examples (files Jev gets right, Kev wrong)", ""]
    rnd = random.Random(7)
    for c in rnd.sample(jev_only, 6):
        k, j = raw["kev-linguist"][c], raw["jev-linguist"][c]
        txt = (BENCH / "files" / cases[c]["sha1_git"]).read_bytes().decode("utf-8", "replace")
        lines = [ln[:100] for ln in txt.splitlines() if ln.strip()][:6]
        kp = f" (position {pos[k['choice']][1] + 1} in its group)" if k["choice"] in pos else ""
        out += [f"**`{cases[c]['filename']}`** — expected **{cases[c]['expected']}** "
                f"([archived file]({SWH}/{cases[c]['qualified_swhid']}/)) · Kev: {k['choice']}{kp}, finalists "
                f"{k['group_winners']} · Jev: {j['choice']}, finalists {j['group_winners']}", "",
                "```", "\n".join(lines).replace("```", "``​`"), "```", ""]

    out += ["## What it means", "",
            "- Kev's gap to Jev is mostly in the first round: with ~200 options per question it favours the options "
            "listed first and seldom answers \"none of these\", so the wrong language often wins a group and the "
            "final gets crowded. The decision model is not the limit by itself — the protocol, long option lists, is.",
            "- For a small local decision model, ask few options: the extension's candidates first (the cascade) "
            "recovers 59 of the 100 sampled files Jev gets right and Kev wrong, keeping 48 of 50 controls; "
            "smaller groups recover 31, reversing the order 20.",
            "- Jev shows no such bias: its group winners are spread almost evenly over the positions.", ""]
    (HERE / "KEV-VS-JEV.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"→ {HERE / 'KEV-VS-JEV.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
